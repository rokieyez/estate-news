# 긴 말을 먼저 찾아야 '종합부동산세' 가 '종부세' 로 잘리거나 겹쳐 잡히지 않는다
_ORDER = sorted(TERMS, key=len, reverse=True)


def explain(text: str, limit: int = 3) -> list[tuple[str, str]]:
    """글에 나온 어려운 말을 나온 순서대로 최대 limit 개. 뜻이 같은 말은 한 번만."""
    flat = " ".join((text or "").split())
    found: list[tuple[int, str, str]] = []
    seen_meanings: set[str] = set()
    taken: list[tuple[int, int]] = []
    for term in _ORDER:
        pos = flat.find(term)
        if pos < 0:
            continue
        # 이미 잡은 긴 말 안에 들어 있는 짧은 말은 건너뛴다 ('종합부동산세' 안의 '부동산')
        if any(start <= pos < end for start, end in taken):
            continue
        meaning = TERMS[term]
        if meaning in seen_meanings:
            continue
        seen_meanings.add(meaning)
        taken.append((pos, pos + len(term)))
        found.append((pos, term, meaning))
    found.sort()
    return [(term, meaning) for _, term, meaning in found[:limit]]
